# .resx and Text.cs are the source of truth; the dashboard needs no network or build-time package.
param([switch]$Check)
$ErrorActionPreference = 'Stop'
$repo = Split-Path -Parent $PSScriptRoot
$app = Join-Path $repo 'HardwareMonitorExtension'
$messages = [ordered]@{}
foreach ($entry in @(@('en', ''), @('zh-Hant', '.zh-Hant'), @('zh-Hans', '.zh-Hans'), @('ja', '.ja'))) {
    $resources = [xml][IO.File]::ReadAllText((Join-Path $app "Localization/Strings$($entry[1]).resx"))
    $values = [ordered]@{}
    foreach ($item in $resources.root.data) { $values[$item.name] = [string]$item.value }
    $messages[$entry[0]] = $values
}
$source = [IO.File]::ReadAllText((Join-Path $app 'Localization/Text.cs'))
$displayKeys = [ordered]@{}
foreach ($match in [regex]::Matches($source, '\["([^"]+)"\] = "([^"]+)"')) {
    $displayKeys[$match.Groups[1].Value] = $match.Groups[2].Value
}
$labelSuffixes = @([regex]::Matches($source, '\("([^"]+)", "([^"]+)"\)') | ForEach-Object {
    ,@($_.Groups[1].Value, $_.Groups[2].Value)
})
$data = [ordered]@{ messages = $messages; displayKeys = $displayKeys; labelSuffixes = $labelSuffixes }
$json = ConvertTo-Json -InputObject $data -Depth 8 -Compress
$result = "// Generated by scripts/Export-DashboardLocales.ps1. Do not edit directly.`nwindow.HardwareMonitorLocales = $json;`n"
$path = Join-Path $app 'Assets/i18n-data.js'
if ($Check) {
    if (-not (Test-Path -LiteralPath $path) -or [IO.File]::ReadAllText($path).Replace("`r`n", "`n") -cne $result) {
        throw 'Dashboard locales are out of date. Run scripts/Export-DashboardLocales.ps1.'
    }
    Write-Output 'Dashboard locale export matches .resx and Text.cs.'
} else {
    [IO.File]::WriteAllText($path, $result, [Text.UTF8Encoding]::new($false))
    Write-Output 'Exported offline dashboard locale dictionaries.'
}
